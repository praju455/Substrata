"""Run measured synthetic evaluation and write its actual results to documentation."""

import argparse
import json

from scripts.dev import ROOT
from substrata.database import build_engine, upgrade_database
from substrata.evaluation import evaluate


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hide-share", type=float, default=1)
    parser.add_argument("--threshold", type=float, default=0.75)
    args = parser.parse_args()
    engine = build_engine(ROOT / "data/substrata.sqlite3")
    try:
        upgrade_database(engine)
        report = evaluate(engine, args.hide_share, args.threshold)
    finally:
        engine.dispose()
    (ROOT / "data/evaluation.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    document = ROOT / "docs/EVALUATION.md"
    marker = "<!-- measured-results -->"
    original = document.read_text(encoding="utf-8").split(marker)[0].rstrip()
    metrics = report["metrics"]
    section = "\n\n" + marker + "\n\n## Measured synthetic fixture results\n\n"
    section += "Generated by `python scripts/dev.py evaluate`. These are measurements on "
    section += "invented data with the deterministic mock, "
    section += "not real-world accuracy or a held-out benchmark.\n\n"
    section += "| Metric | Measured value |\n|---|---:|\n"
    section += "\n".join(f"| {name} | {value:g} |" for name, value in metrics.items()) + "\n\n"
    section += f"Seed: 42; hide share: {args.hide_share:g}; threshold: {args.threshold:g}. "
    section += f"Fixture SHA-256: `{report['fixture_sha256']}`.\n\n"
    section += report["warning_assumption"] + "\n\n"
    section += "The mock uses a fixed ownership sentence template and frozen reliability weights. "
    section += "No parameter tuning, split-based model training or "
    section += "independent generalisation test was performed. "
    section += "Raw expected/predicted IDs and errors are in `data/evaluation.json`; "
    section += "the run, examples and metrics are persisted in the evaluation tables.\n"
    document.write_text(original + section, encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
